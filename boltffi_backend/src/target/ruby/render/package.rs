//! The gem around the extension: `lib/`, `extconf.rb`, the runtime header,
//! and the gemspec.

use askama::Template;

use crate::{
    core::{FilePath, GeneratedFile, Result},
    target::ruby::syntax::{ConstantPath, Literal},
};

/// Handwritten C support code that every generated extension includes.
const RUNTIME_HEADER: &str = include_str!("../../../../templates/target/ruby/boltffi_ruby.h");

#[derive(Template)]
#[template(path = "target/ruby/lib.rb", escape = "none")]
struct LibTemplate<'package> {
    module: &'package ConstantPath,
    extension_path: Literal,
}

#[derive(Template)]
#[template(path = "target/ruby/extconf.rb", escape = "none")]
struct ExtconfTemplate<'package> {
    stem: &'package str,
    extension: Literal,
    artifact: Literal,
    manifest: Option<Literal>,
    active_features: Literal,
    feature_args: Vec<Literal>,
}

#[derive(Template)]
#[template(path = "target/ruby/gem.gemspec", escape = "none")]
struct GemspecTemplate {
    gem: Literal,
    version: Literal,
    summary: Literal,
    extconf: Literal,
}

/// Names that the package files share.
pub struct Package<'package> {
    pub gem: &'package str,
    pub version: &'package str,
    pub stem: &'package str,
    pub module: &'package ConstantPath,
    pub artifact: &'package str,
    pub cargo_manifest: Option<&'package str>,
    pub active_features: &'package str,
    pub feature_args: &'package [String],
    pub crate_name: &'package str,
}

impl Package<'_> {
    /// The directory that holds the extension sources.
    pub fn extension_dir(&self) -> String {
        format!("ext/{}", self.stem)
    }

    pub fn render(&self) -> Result<Vec<GeneratedFile>> {
        let extension_dir = self.extension_dir();
        Ok(vec![
            GeneratedFile::new(
                FilePath::new(format!("lib/{}.rb", self.stem))?,
                LibTemplate {
                    module: self.module,
                    extension_path: Literal::string(&format!("{0}/{0}", self.stem)),
                }
                .render()?,
            ),
            GeneratedFile::new(
                FilePath::new(format!("{extension_dir}/extconf.rb"))?,
                ExtconfTemplate {
                    stem: self.stem,
                    extension: Literal::string(self.stem),
                    artifact: Literal::string(self.artifact),
                    manifest: self.cargo_manifest.map(Literal::string),
                    active_features: Literal::string(self.active_features),
                    feature_args: self
                        .feature_args
                        .iter()
                        .map(|argument| Literal::string(argument))
                        .collect(),
                }
                .render()?,
            ),
            GeneratedFile::new(
                FilePath::new(format!("{extension_dir}/boltffi_ruby.h"))?,
                RUNTIME_HEADER,
            ),
            GeneratedFile::new(
                FilePath::new(format!("{}.gemspec", self.gem))?,
                GemspecTemplate {
                    gem: Literal::string(self.gem),
                    version: Literal::string(self.version),
                    summary: Literal::string(&format!(
                        "Ruby bindings for {}, generated by BoltFFI",
                        self.crate_name
                    )),
                    extconf: Literal::string(&format!("{extension_dir}/extconf.rb")),
                }
                .render()?,
            ),
        ])
    }
}
